package com.hongxiang.kpilot.library

/**
 * Reads the EXTH metadata and one embedded image record from a MOBI/AZW3 file.
 * Mirrors the iOS MOBICoverExtractor and never decodes book text.
 */
object MobiCoverExtractor {
    data class Cover(val data: ByteArray, val thumbnailFilename: String?)

    private val thumbnailName = Regex("thumbnail_([A-Za-z0-9_-]{1,128})_(EBOK|PDOC)_portrait\\.jpg")
    private val jpegSignature = byteArrayOf(0xFF.toByte(), 0xD8.toByte(), 0xFF.toByte())
    private val pngSignature = byteArrayOf(
        0x89.toByte(), 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A
    )
    private val gifSignature = "GIF8".toByteArray(Charsets.US_ASCII)
    private val mobiSignature = "MOBI".toByteArray(Charsets.US_ASCII)
    private val exthSignature = "EXTH".toByteArray(Charsets.US_ASCII)

    /** Kindle uses EXTH 113 (content ID) and 501 (content type) as the thumbnail cache key. */
    fun thumbnailFilename(contentId: String?, contentType: String?): String? {
        if (contentId.isNullOrEmpty() || contentType !in setOf("EBOK", "PDOC")) return null
        // The ID is ASCII in Kindle files, so character count and UTF-8 byte count match.
        if (contentId.length > 128) return null
        if (!contentId.all { it in '0'..'9' || it in 'A'..'Z' || it in 'a'..'z' || it == '-' || it == '_' }) return null
        return "thumbnail_${contentId}_${contentType}_portrait.jpg"
    }

    /** Only basenames generated by [thumbnailFilename] may be used as a remote write target. */
    fun isSafeThumbnailFilename(name: String): Boolean {
        val match = thumbnailName.matchEntire(name) ?: return false
        return thumbnailFilename(match.groupValues[1], match.groupValues[2]) == name
    }

    fun cover(data: ByteArray): Cover? {
        val count = uint16(data, 76L) ?: return null
        if (count <= 0) return null
        val headerEnd = 78L + count * 8L
        if (headerEnd > data.size) return null

        val offsets = LongArray(count + 1)
        for (index in 0 until count) {
            val value = uint32(data, 78L + index * 8L) ?: return null
            if (value >= data.size || value < headerEnd) return null
            if (index > 0 && value <= offsets[index - 1]) return null
            offsets[index] = value
        }
        offsets[count] = data.size.toLong()

        val mobiStart = offsets[0] + 16
        if (!startsWith(data, mobiStart, mobiSignature)) return null
        val headerLength = uint32(data, mobiStart + 4) ?: return null
        if (headerLength < 96 || mobiStart + headerLength > offsets[1]) return null
        val firstImageRecord = uint32(data, mobiStart + 92) ?: return null

        val exthStart = mobiStart + headerLength
        if (!startsWith(data, exthStart, exthSignature)) return null
        val exthLength = uint32(data, exthStart + 4) ?: return null
        val exthCount = uint32(data, exthStart + 8) ?: return null
        if (exthLength < 12 || exthStart + exthLength > offsets[1]) return null
        if (exthCount > (exthLength - 12) / 8) return null

        var position = exthStart + 12
        var coverOffset: Long? = null
        var thumbnailOffset: Long? = null
        var contentId: String? = null
        var contentType: String? = null
        repeat(exthCount.toInt()) {
            val type = uint32(data, position) ?: return null
            val length = uint32(data, position + 4) ?: return null
            if (length < 8 || position + length > exthStart + exthLength) return null
            when (type) {
                201L -> if (length >= 12) coverOffset = uint32(data, position + 8)
                202L -> if (length >= 12) thumbnailOffset = uint32(data, position + 8)
                113L, 501L -> {
                    val value = data.copyOfRange((position + 8).toInt(), (position + length).toInt())
                        .toString(Charsets.UTF_8)
                    if (type == 113L) contentId = value else contentType = value
                }
            }
            position += length
        }

        for (offset in listOfNotNull(coverOffset, thumbnailOffset)) {
            val recordIndex = firstImageRecord + offset
            if (recordIndex < 0 || recordIndex >= count) continue
            val start = offsets[recordIndex.toInt()]
            val end = offsets[recordIndex.toInt() + 1]
            if (start >= end || end > data.size) continue
            val candidate = data.copyOfRange(start.toInt(), end.toInt())
            if (isImage(candidate)) return Cover(candidate, thumbnailFilename(contentId, contentType))
        }
        return null
    }

    private fun isImage(data: ByteArray): Boolean =
        startsWith(data, 0L, jpegSignature) ||
            startsWith(data, 0L, pngSignature) ||
            startsWith(data, 0L, gifSignature)

    private fun uint16(data: ByteArray, offset: Long): Int? {
        if (offset < 0 || offset + 2 > data.size) return null
        val at = offset.toInt()
        return ((data[at].toInt() and 0xFF) shl 8) or (data[at + 1].toInt() and 0xFF)
    }

    private fun uint32(data: ByteArray, offset: Long): Long? {
        if (offset < 0 || offset + 4 > data.size) return null
        val at = offset.toInt()
        return ((data[at].toLong() and 0xFF) shl 24) or
            ((data[at + 1].toLong() and 0xFF) shl 16) or
            ((data[at + 2].toLong() and 0xFF) shl 8) or
            (data[at + 3].toLong() and 0xFF)
    }

    private fun startsWith(data: ByteArray, offset: Long, signature: ByteArray): Boolean {
        if (offset < 0 || offset + signature.size > data.size) return false
        val start = offset.toInt()
        for (index in signature.indices) if (data[start + index] != signature[index]) return false
        return true
    }
}
